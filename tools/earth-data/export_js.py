def rle_uint8(arr):
    """Run-length encode a uint8 array as (value, LEB128 run length) pairs."""
    flat = np.asarray(arr, dtype=np.uint8).ravel()
    change = np.nonzero(np.diff(flat))[0] + 1
    starts = np.concatenate([[0], change])
    lengths = np.diff(np.concatenate([starts, [len(flat)]]))
    out = bytearray()
    for s, n in zip(starts, lengths):
        out.append(int(flat[s]))
        n = int(n)
        while True:
            byte = n & 0x7F
            n >>= 7
            if n:
                out.append(byte | 0x80)
            else:
                out.append(byte)
                break
    return bytes(out), len(starts)


def rle_decode(data, length):
    out = np.empty(length, dtype=np.uint8)
    i = pos = 0
    while pos < len(data):
        v = data[pos]
        pos += 1
        n = shift = 0
        while True:
            b = data[pos]
            pos += 1
            n |= (b & 0x7F) << shift
            shift += 7
            if not b & 0x80:
                break
        out[i:i + n] = v
        i += n
    assert i == length
    return out


d = np.load(SRC)
elev = np.rint(d['elev']).astype('<i2')
cont = np.rint(np.clip(d['cont_frac'], 0, 1) * 255).astype(np.uint8)
plate = d['plate_id'].astype(np.uint8)
codes = [str(c) for c in d['codes']]
pole_nnr = d['pole_nnr']
c0, c1 = (float(x) for x in d['fit'])
H, W = elev.shape

cont_rle, cont_runs = rle_uint8(cont)
plate_rle, plate_runs = rle_uint8(plate)
assert (rle_decode(cont_rle, cont.size) == cont.ravel()).all()
assert (rle_decode(plate_rle, plate.size) == plate.ravel()).all()

plates = []
for i, code in enumerate(codes):
    lat, lon, rate = (float(x) for x in pole_nnr[i])
    plates.append({'code': code, 'name': NAMES[code],
                   'pole_lat': round(lat, 4), 'pole_lon': round(lon, 4), 'rate': round(rate, 5)})

b64 = lambda b: base64.b64encode(b).decode('ascii')
header = """// Present-day Earth for tectonics.js. Generated by tools/earth-data/export_js.py; do not edit by hand.
//
// Rasters are equirectangular, %(w)d x %(h)d pixels of %(res)g degrees. Row 0 is the northernmost band and column 0
// starts at 180 W, so pixel (row, col) is centred on lat = 90 - (row+0.5)*%(res)g, lon = -180 + (col+0.5)*%(res)g.
//
//  elevation    Int16 little-endian, metres above mean sea level, area-weighted mean over each pixel.
//               ETOPO1 Ice Surface (Amante & Eakins 2009, NOAA NGDC), 1 arc-minute grid sampled at 0.1 degree.
//  continental  Uint8 0-255, fraction of the pixel NOT covered by dated oceanic crust, run-length encoded.
//               Seton et al. (2020) seafloor age grid, EarthByte, CC BY 4.0.
//  plate        Uint8 index into `plates`, run-length encoded (value, LEB128 run length).
//               PB2002 plate boundaries (Bird 2003, G-cubed 4(3), 1027, doi:10.1029/2001GC000252).
//  plates       PB2002 Euler poles converted from Pacific-fixed to the no-net-rotation frame
//               (rate in degrees per million years, counter-clockwise positive).
//  depth_age    Median seafloor depth vs. age, 0-105 Myr, from the two grids above: depth = intercept + slope * age.
""" % {'w': W, 'h': H, 'res': 360 / W}

body = {
    'width': W, 'height': H,
    'elevation': b64(elev.tobytes()),
    'continental': b64(cont_rle),
    'plate': b64(plate_rle),
    'plates': plates,
    'depth_age': {'intercept': round(c0, 1), 'slope': round(c1, 3)},
}
with open(DST, 'w', newline='\n') as f:
    f.write(header)
    f.write("'use strict';\n\nconst EarthData = ")
    f.write(json.dumps(body, indent=1, ensure_ascii=False).replace('\n "', '\n    "'))
    f.write(';\n')

print('wrote %s (%.0f KB): elevation %d B, continental %d runs/%d B, plate %d runs/%d B' % (
    DST, os.path.getsize(DST) / 1024, elev.nbytes, cont_runs, len(cont_rle), plate_runs, len(plate_rle)))
print('depth-age fit: intercept %.1f slope %.3f' % (c0, c1))
